const {chromium}=require('playwright'),assert=require('node:assert/strict')
;(async()=>{
 const browser=await chromium.launch({headless:true,...(process.env.CHROME_EXECUTABLE?{executablePath:process.env.CHROME_EXECUTABLE}:{})})
 try{
  const page=await browser.newPage(),errors=[];page.on('pageerror',e=>errors.push(e.message))
  const base=process.argv[2]||'http://127.0.0.1:8012'
  let voiceRequests=0
  page.on('request',r=>{if(r.url().endsWith('/api/voice/commentary'))voiceRequests++})
  await page.goto(`${base}/?story=last-gasp#matchday`)
  const listen=page.getByRole('button',{name:'Listen',exact:true})
  await listen.waitFor();await page.waitForFunction(()=>!document.querySelector('.live-companion button').disabled)
  await listen.click()
  await page.getByText('Commentary ready · follows playback',{exact:true}).waitFor({timeout:120000})
  const prepared=voiceRequests,play=page.getByRole('button',{name:'Play highlight',exact:true}),pause=page.getByRole('button',{name:'Pause play',exact:true})
  const slider=page.getByRole('slider',{name:'Replay position'})
  await play.click();await page.waitForTimeout(700);await pause.click()
  const paused=Number(await slider.inputValue());await page.waitForTimeout(500)
  assert.equal(Number(await slider.inputValue()),paused)
  await play.click();await page.waitForTimeout(400);await pause.click()
  assert(Number(await slider.inputValue())>paused)
  await slider.fill('400')
  assert.equal(Number(await slider.inputValue()),400)
  await page.getByRole('combobox',{name:'Pitch replay speed'}).selectOption('1.5')
  await play.click();await page.waitForTimeout(400);await pause.click()
  assert(Number(await slider.inputValue())>400)
  await page.getByRole('button',{name:/^Restart/}).click()
  assert.equal(Number(await slider.inputValue()),0)
  assert.equal(voiceRequests,prepared)
  for(const width of [360,390,760]){
   await page.setViewportSize({width,height:844})
   assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),`overflow at ${width}`)
  }
  await page.emulateMedia({reducedMotion:'reduce'})
  await play.click();await page.waitForTimeout(300);await pause.click()
  assert(Number(await slider.inputValue())>0,'Reduced motion must still permit voiced playback')
  await page.goto(`${base}/#live`)
  await page.getByRole('button',{name:'Play match',exact:true}).waitFor()
  assert.equal(await page.getByRole('button',{name:'Listen',exact:true}).count(),0)
  assert.equal(await page.getByRole('link',{name:'Match Centre',exact:true}).getAttribute('aria-current'),'page')
  assert.equal(voiceRequests,prepared,'Full match requested speech')
  // Deliberate preparation failure must not launch partial or stale audio.
  await page.route('**/api/voice/commentary',r=>r.fulfill({status:503,body:'unavailable'}))
  await page.goto(`${base}/?story=one-touch#matchday`)
  await listen.waitFor();await page.waitForFunction(()=>!document.querySelector('.live-companion button').disabled)
  await listen.click()
  await page.getByText(/Commentary could not load/).waitFor()
  assert.equal(await listen.getAttribute('aria-pressed'),'false')
  assert(!(await page.getByRole('button',{name:'Show ball movement',exact:true}).isDisabled()))
  assert.deepEqual(errors,[])
  console.log('PASS voiced highlight controls: pause/resume, seek, speed, restart, mobile widths, reduced motion, preparation failure; full matches have no narration or speech requests.')
 }finally{await browser.close()}
})().catch(e=>{console.error(e);process.exit(1)})
