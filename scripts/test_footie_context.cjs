// Run against a local preview without --azure. Opening a panel never sends a question.
const {chromium}=require('playwright')
const assert=require('node:assert/strict')
;(async()=>{
 const browser=await chromium.launch({headless:true,executablePath:process.env.CHROME_EXECUTABLE||'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome'})
 try{
  const page=await browser.newPage({viewport:{width:1440,height:1000}}),requests=[],errors=[]
  page.on('pageerror',e=>errors.push(e.message))
  page.on('request',r=>{if(r.url().endsWith('/api/fan/assistant/ask'))requests.push(r.postDataJSON())})
  const base=process.argv[2]||'http://127.0.0.1:8018'
  assert.equal((await (await page.request.get(base+'/api/fan/assistant/config')).json()).natural_language,false,'Use a non-Azure preview')
  await page.goto(base+'/#football/player/rh09')
  await page.getByRole('combobox',{name:'Statistics period'}).selectOption('2025-26')
  await page.getByRole('button',{name:'Ask Footie'}).click()
  let dialog=page.getByRole('dialog',{name:'Ask Footie',exact:true})
  await dialog.getByRole('textbox',{name:'Ask a football question'}).waitFor()
  assert.equal(requests.length,0)
  assert.equal(await dialog.getByRole('combobox',{name:'Player context'}).count(),0)
  await dialog.getByRole('button',{name:'Send question'}).click()
  await dialog.locator('.ft-story').waitFor()
  assert.equal(requests[0].player_id,'rh09');assert.equal(requests[0].season,'2025-26')
  assert.equal(requests[0].cutoff,null)
  assert.match(await dialog.locator('.ft-story').innerText(),/14/)
  await dialog.screenshot({path:'var/footie-context-profile.png'})
  await page.keyboard.press('Escape')
  await dialog.waitFor({state:'hidden'})
  assert.equal(await page.evaluate(()=>document.activeElement?.textContent?.includes('Ask Footie')),true)
  assert.equal(await page.getByRole('combobox',{name:'Statistics period'}).inputValue(),'2025-26')
  // A parent-linked Matchday highlight uses its source match time, not the rebased 12th minute.
  await page.goto(base+'/?story=level-first#matchday')
  const slider=page.getByRole('slider',{name:'Replay position'})
  await slider.focus();await slider.press('End')
  await page.getByRole('button',{name:'Ask Footie'}).click()
  dialog=page.getByRole('dialog',{name:'Ask Footie',exact:true})
  await dialog.getByRole('textbox',{name:'Ask a football question'}).waitFor()
  assert.equal(requests.length,1)
  await dialog.getByRole('button',{name:'Send question'}).click()
  await dialog.locator('.ft-answer').waitFor()
  const second=requests[1]
  assert.equal(second.match_id,'synthetic-32fe41c5d304ce68d7d9')
  assert.equal(second.cutoff.period,1);assert(second.cutoff.elapsed_ms>2000000)
  assert.match(second.event_id,/^a\d+/);assert.equal(second.event_revision,1)
  assert.match(await dialog.locator('.ft-answer').innerText(),/Owen Cole/)
  assert(!await page.getByRole('button',{name:/^Pause play/}).count())
  await page.getByRole('button',{name:'Close Footie'}).click()
  // Match Centre freezes the currently animated action and preserves the paused sequence.
  await page.goto(base+'/?match=wyscout-2058017#gi')
  await page.getByRole('button',{name:'Moments',exact:true}).click()
  // Exercise the original moment entry point in the opening passage, before
  // rolling comparisons are eligible to replace it with an insight question.
  const matchTimeline=page.getByRole('slider',{name:'Match timeline'})
  await matchTimeline.focus();await matchTimeline.press('Home')
  const progress=page.getByRole('slider',{name:'Play sequence progress'})
  await progress.focus();await progress.press('End')
  await page.getByRole('button',{name:'Ask Footie'}).click()
  dialog=page.getByRole('dialog',{name:'Ask Footie',exact:true})
  await dialog.getByRole('textbox',{name:'Ask a football question'}).waitFor()
  await dialog.getByRole('button',{name:'Send question'}).click()
  await dialog.locator('.ft-answer').waitFor()
  assert.equal(requests[2].match_id,'wyscout-2058017')
  assert.match(requests[2].event_id,/^wyscout-/)
  const frozen=JSON.stringify(requests[2].cutoff)
  for(const width of [390,360]){
   await page.setViewportSize({width,height:844})
   assert(await dialog.evaluate(el=>el.scrollWidth<=el.clientWidth),'modal horizontal overflow')
   assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'page horizontal overflow')
  }
  const closeBox=await dialog.getByRole('button',{name:'Close Footie'}).boundingBox()
  assert(closeBox.y>=0&&closeBox.y+closeBox.height<844,'Close button must stay visible')
  await dialog.screenshot({path:'var/footie-context-mobile.png'})
  assert.equal(JSON.stringify(requests[2].cutoff),frozen)
  await page.keyboard.press('Escape')
  assert.equal(await progress.inputValue(),'1')
  assert.deepEqual(errors,[])
  console.log('PASS Footie context: profile season, no automatic questions, source-time highlight handoff, Match Centre event revision, pause/return, focus restoration, mobile layout, no browser errors.')
 }finally{await browser.close()}
})().catch(e=>{console.error(e);process.exit(1)})
