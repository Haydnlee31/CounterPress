const {chromium}=require('playwright')
const assert=require('node:assert/strict')
const fs=require('node:fs')
;(async()=>{
 const browser=await chromium.launch({headless:true,...(process.env.CHROME_EXECUTABLE?{executablePath:process.env.CHROME_EXECUTABLE}:{})})
 try{
  const page=await browser.newPage({viewport:{width:1440,height:1100},reducedMotion:'no-preference'})
  const errors=[];page.on('pageerror',e=>errors.push(e.message))
  const base=process.argv[2]||'http://127.0.0.1:8010'
  fs.mkdirSync('var',{recursive:true})
  for(const [id,title,score] of [['one-touch','Pass, move, finish',3],['breakaway','From halfway to goal',2]]){
   await page.goto(`${base}/?story=${id}#matchday`)
   const pitch=page.getByRole('region',{name:'Match pitch',exact:true})
   await pitch.getByRole('slider',{name:'Replay position'}).waitFor()
   assert.equal(await page.locator('.fan-replay-card').count(),3)
   assert((await page.locator('.fan-replay-card.is-active').innerText()).includes(title))
   assert.equal(await pitch.locator('.fan-pitch-player').count(),22)
   assert.equal(await pitch.locator('.is-distant').count(),0)
   assert.equal(await pitch.getByRole('button',{name:'Near the ball'}).count(),0)
   assert.equal(await page.locator('pre').count(),0)
   assert.match(await page.locator('.fan-score-center > span').innerText(),new RegExp(`${score-1}\\s*:\\s*0`))
   await page.screenshot({path:`var/replay-gallery-${id}.png`,fullPage:true,animations:'disabled'})
   await pitch.getByLabel('Pitch replay speed').selectOption('1.5')
   await pitch.getByRole('button',{name:/Play sequence/}).click()
   await pitch.locator('.fan-goal-banner').waitFor({timeout:20000})
   await pitch.getByRole('button',{name:/Play sequence/}).waitFor()
   assert.match(await page.locator('.fan-score-center > span').innerText(),new RegExp(`${score}\\s*:\\s*0`))
   // Keyboard scrubbing must retract the score; restart must reset every control.
   await pitch.getByRole('slider',{name:'Replay position'}).focus()
   await page.keyboard.press('Home')
   assert.equal(await pitch.locator('.fan-goal-banner').count(),0)
   await page.waitForFunction(expected=>document.querySelector('.fan-score-center > span')?.textContent?.trim().replace(/\s/g,'')===`${expected}:0`,score-1)
   assert.match(await page.locator('.fan-score-center > span').innerText(),new RegExp(`${score-1}\\s*:\\s*0`))
   await pitch.getByRole('button',{name:/Restart/}).click()
   assert.equal(await pitch.getByRole('slider',{name:'Replay position'}).inputValue(),'0')
  }
  await page.getByRole('button',{name:/Pass, move, finish/}).click()
  await page.locator('.fan-replay-card.is-active').filter({hasText:'Pass, move, finish'}).waitFor()
  await page.setViewportSize({width:390,height:844})
  const pitch=page.getByRole('region',{name:'Match pitch',exact:true})
  await pitch.scrollIntoViewIfNeeded()
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth))
  assert.equal(await pitch.locator('.fan-pitch-player').count(),22)
  assert((await pitch.locator('.fan-pitch-controls').boundingBox()).y < (await pitch.locator('.fan-pitch-canvas').boundingBox()).y)
  await page.screenshot({path:'var/replay-gallery-mobile.png',fullPage:true,animations:'disabled'})
  await page.getByLabel('Language',{exact:true}).selectOption('zh-Hans')
  await page.getByRole('slider',{name:'回放位置'}).waitFor()
  assert((await page.locator('.fan-replay-card.is-active').innerText()).includes('传球'))
  await page.emulateMedia({reducedMotion:'reduce'})
  await page.getByRole('button',{name:'查看传球落点'}).waitFor()
  assert.deepEqual(errors,[])
  console.log('PASS: three replay cards, both new deep links and full animations, 22 persistent players, score/goal timing, keyboard scrub/rewind, restart, speed, mobile, bilingual and reduced motion; no browser errors.')
 }finally{await browser.close()}
})().catch(e=>{console.error(e);process.exitCode=1})
