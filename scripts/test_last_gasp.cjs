const {chromium}=require('playwright')
const assert=require('node:assert/strict')
const fs=require('node:fs')
;(async()=>{
 const browser=await chromium.launch({headless:true,...(process.env.CHROME_EXECUTABLE?{executablePath:process.env.CHROME_EXECUTABLE}:{})})
 try{
  const page=await browser.newPage({viewport:{width:1440,height:1100},reducedMotion:'no-preference'})
  const errors=[];page.on('pageerror',e=>errors.push(e.message))
  const base=process.argv[2]||'http://127.0.0.1:8010'
  await page.goto(`${base}/?story=last-gasp#matchday`)
  const pitch=page.getByRole('region',{name:'Match pitch',exact:true})
  const score=page.locator('.fan-score-center > span')
  await pitch.getByRole('button',{name:/Play sequence/}).waitFor()
  await page.waitForFunction(()=>/2\s*:\s*1/.test(document.querySelector('.fan-score-center > span')?.textContent||''))
  assert.match(await score.innerText(),/2\s*:\s*1/)
  assert.equal(await pitch.locator('.fan-pitch-player').count(),22)
  assert.equal(await page.locator('pre').count(),0)
  assert.match(await page.locator('.fan-replay-context a').getAttribute('href'),/t=560s/)
  await pitch.getByRole('button',{name:/Play sequence/}).click()
  await pitch.locator('.fan-goal-banner').waitFor({timeout:35000})
  await page.waitForFunction(()=>/3\s*:\s*1/.test(document.querySelector('.fan-score-center > span')?.textContent||''))
  assert.match(await score.innerText(),/3\s*:\s*1/)
  await pitch.getByRole('button',{name:/Play sequence/}).waitFor()
  fs.mkdirSync('var',{recursive:true})
  await page.locator('main').screenshot({path:'var/last-gasp-desktop.png'})
  await pitch.getByRole('button',{name:'Previous play',exact:true}).click()
  await page.waitForFunction(()=>/2\s*:\s*1/.test(document.querySelector('.fan-score-center > span')?.textContent||''))
  assert.match(await score.innerText(),/2\s*:\s*1/)
  assert.equal(await pitch.locator('.fan-goal-banner').count(),0)
  await page.emulateMedia({reducedMotion:'reduce'})
  await pitch.getByRole('button',{name:'Next play',exact:true}).click()
  await pitch.getByRole('button',{name:'Show ball movement',exact:true}).click()
  await page.waitForFunction(()=>/3\s*:\s*1/.test(document.querySelector('.fan-score-center > span')?.textContent||''))
  assert.match(await score.innerText(),/3\s*:\s*1/)
  await page.setViewportSize({width:390,height:844})
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth))
  await pitch.screenshot({path:'var/last-gasp-mobile.png'})
  await page.getByLabel('Language',{exact:true}).selectOption('zh-Hans')
  await page.getByRole('region',{name:'比赛球场',exact:true}).waitFor()
  assert((await page.locator('.fan-replay-card.is-active').innerText()).includes('逆转'))
  await page.getByLabel('Language',{exact:true}).selectOption('en')
  await page.getByLabel('Explore a story',{exact:true}).selectOption('increase')
  await page.getByLabel('1 to 4',{exact:true}).waitFor()
  await page.getByRole('button',{name:/Last-second turnaround/}).click()
  await page.locator('.fan-turnaround-story').waitFor()
  await page.waitForFunction(()=>/2\s*:\s*1/.test(document.querySelector('.fan-score-center > span')?.textContent||''))
  assert.match(await score.innerText(),/2\s*:\s*1/)
  assert.deepEqual(errors,[])
  console.log('PASS: last-gasp deep link, 22 players, full animated sequence, 2:1 → 3:1, rewind, reduced motion, mobile, bilingual, story switching; no browser errors.')
 }finally{await browser.close()}
})().catch(e=>{console.error(e);process.exitCode=1})
