const {chromium}=require('playwright')
const assert=require('node:assert/strict')
;(async()=>{
 const browser=await chromium.launch({headless:true,...(process.env.CHROME_EXECUTABLE?{executablePath:process.env.CHROME_EXECUTABLE}:{})})
 try{
  const page=await browser.newPage({viewport:{width:1440,height:1000}})
  const errors=[];page.on('pageerror',e=>errors.push(e.message))
  const base=process.argv[2]||'http://127.0.0.1:8011'
  await page.goto(`${base}/?match=synthetic-32fe41c5d304ce68d7d9#live`)
  await page.getByRole('button',{name:'Play match',exact:true}).waitFor()
  const score=page.locator('.live-score strong')
  assert.equal(await score.innerText(),'0 : 0')
  assert.equal(await page.locator('.fan-pitch-player').count(),22)
  const slider=page.getByRole('slider',{name:'Match clock'})
  const seek=async value=>{
   await slider.evaluate((el,value)=>{Object.getOwnPropertyDescriptor(HTMLInputElement.prototype,'value').set.call(el,String(value));el.dispatchEvent(new Event('input',{bubbles:true}));el.dispatchEvent(new Event('change',{bubbles:true}))},value)
   await page.waitForTimeout(100)
  }
  await seek(1207000)
  assert.equal(await score.innerText(),'0 : 1')
  const companion=page.getByRole('region',{name:'Live Companion',exact:true})
  await companion.getByRole('button',{name:/Follow the play/}).click()
  await companion.getByRole('button',{name:'What just happened?'}).click()
  assert((await companion.innerText()).includes('Jude Rivers'))
  await seek(0)
  assert.equal(await score.innerText(),'0 : 0')
  assert.equal(await companion.getByText(/Actions behind this answer/).count(),0)
  await page.getByRole('button',{name:'Play match',exact:true}).click()
  await page.waitForTimeout(1700)
  assert(Number(await slider.inputValue())>1000)
  await page.getByRole('button',{name:'Pause match',exact:true}).click()
  await seek(2699000)
  await page.getByRole('button',{name:'Play match',exact:true}).click()
  await page.getByRole('button',{name:'Start second half',exact:true}).waitFor()
  await page.getByRole('button',{name:'Start second half',exact:true}).click()
  await page.waitForTimeout(1200)
  assert(Number(await slider.inputValue())>2700000)
  await page.getByRole('button',{name:'Pause match',exact:true}).click()
  await seek(5400000)
  assert.equal(await score.innerText(),'2 : 2')
  await page.getByRole('button',{name:'Replay match',exact:true}).click()
  await page.getByRole('button',{name:'Pause match',exact:true}).click()
  assert.equal(await score.innerText(),'0 : 0')
  await page.screenshot({path:'var/full-match-desktop.png',fullPage:true})
  for(const width of [360,390,760]){
   await page.setViewportSize({width,height:844})
   assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),`overflow at ${width}`)
  }
  await page.setViewportSize({width:390,height:844})
  await page.screenshot({path:'var/full-match-mobile.png',fullPage:true})
  await page.getByRole('combobox',{name:'Commentary language'}).selectOption('zh-Hans')
  await page.getByRole('button',{name:'播放比赛',exact:true}).waitFor()
  assert.deepEqual(errors,[])
  console.log('PASS full match: kickoff/goal/rewind/full-time scores, 22 players, grounded answers, halftime/resume/restart, English/Mandarin, desktop and phone layouts.')
 }finally{await browser.close()}
})().catch(e=>{console.error(e);process.exit(1)})
