const {chromium}=require('playwright')
const assert=require('node:assert/strict')
const fs=require('node:fs')
;(async()=>{
 const browser=await chromium.launch({headless:true,...(process.env.CHROME_EXECUTABLE?{executablePath:process.env.CHROME_EXECUTABLE}:{})})
 try{
  const page=await browser.newPage({viewport:{width:1440,height:1000},reducedMotion:'reduce'})
  const errors=[];page.on('pageerror',e=>errors.push(e.message))
  const base=process.argv[2]||'http://127.0.0.1:8010'
  await page.goto(`${base}/?story=breakaway#matchday`)
  await page.getByRole('heading',{level:1,name:'From halfway to goal'}).waitFor()
  const nav=()=>page.getByRole('navigation',{name:'Workspace',exact:true})
  await nav().getByRole('link',{name:'Explore data',exact:true}).click()
  await page.getByRole('heading',{level:1,name:'From halfway to goal'}).waitFor()
  assert.equal(new URL(page.url()).searchParams.get('story'),'breakaway')
  await nav().getByRole('link',{name:'Match Centre',exact:true}).click()
  await page.getByRole('heading',{name:'Eastbridge 4 – 2 Northport'}).waitFor()
  await page.getByRole('button',{name:'Moments',exact:true}).click()
  await page.locator('.gi-filter-disclosure summary').click()
  await page.getByRole('group',{name:'Team',exact:true}).getByRole('button',{name:'Northport',exact:true}).click()
  await page.getByRole('group',{name:'Explore actions'}).getByRole('button',{name:'All shots',exact:true}).click()
  await page.getByRole('button',{name:/Shot map/}).click()
  await page.locator('.gi-shot-pin').last().focus();await page.keyboard.press('Enter')
  const selected=await page.locator('.gi-detail-heading').innerText()
  await nav().getByRole('link',{name:'Matchday',exact:true}).click()
  await page.getByRole('heading',{level:1,name:'From halfway to goal'}).waitFor()
  await nav().getByRole('link',{name:'Match Centre',exact:true}).click()
  await page.getByRole('button',{name:'Moments',exact:true}).click()
  await page.locator('.gi-filter-disclosure summary').click()
  await page.locator('.gi-shot-pin').first().waitFor()
  assert.equal(await page.locator('.gi-shot-pin').count(),14)
  assert.equal(await page.locator('.gi-detail-heading').innerText(),selected)
  assert.equal(await page.getByRole('group',{name:'Team',exact:true}).getByRole('button',{name:'Northport',exact:true}).getAttribute('aria-pressed'),'true')
  await page.locator('.cp-library summary').click()
  await page.locator('.cp-library-menu').getByRole('link',{name:/Pass, move, finish/}).click()
  await page.getByRole('heading',{level:1,name:'Pass, move, finish'}).waitFor()
  assert.equal(new URL(page.url()).searchParams.get('story'),'one-touch')
  await page.locator('.cp-tools summary').click()
  await page.locator('.cp-tools-menu').getByRole('link',{name:/Producer Studio/}).click()
  await page.getByRole('heading',{name:'A story you can stand behind.'}).waitFor()
  assert.equal(await page.locator('.cp-header').count(),1)
  await page.locator('.cp-tools summary').click()
  await page.locator('.cp-tools-menu').getByRole('link',{name:/Advanced analysis/}).click()
  await page.getByLabel('Local viewer').waitFor()
  assert.equal(await page.getByRole('link',{name:'CounterPress home',exact:true}).count(),1)
  await nav().getByRole('link',{name:'Matchday',exact:true}).click()
  await page.getByRole('heading',{level:1,name:'Pass, move, finish'}).waitFor()
  await page.locator('.cp-library summary').focus();await page.keyboard.press('Enter');await page.keyboard.press('Escape')
  assert.equal(await page.locator('.cp-library').getAttribute('open'),null)
  await page.getByRole('button',{name:/choose a side/}).click()
  await page.getByLabel('Follow a team',{exact:true}).selectOption('northport')
  await page.getByRole('button',{name:'Done',exact:true}).click()
  fs.mkdirSync('var',{recursive:true})
  for(const width of [1440,390,360]){
   await page.setViewportSize({width,height:1000})
   for(const route of ['matchday','explore','gi']){
    await nav().getByRole('link',{name:route==='matchday'?'Matchday':route==='explore'?'Explore data':'Match Centre',exact:true}).click()
    await page.locator('main h1').waitFor()
    if(route==='gi'){await page.locator('.gi-overview').waitFor();assert.equal(await page.locator('.gi').getAttribute('data-club'),'northport')}
    else await page.locator('.fan-pitch-player').first().waitFor()
    assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),`${route} overflow ${width}`)
    await page.screenshot({path:`var/unified-${route}-${width}.png`,fullPage:true})
   }
  }
  assert.deepEqual(errors,[])
  console.log('PASS unified shell: highlight context across views, GI filters/shot selection restored, library navigation, Studio/advanced access, single brand header, Escape dismissal, desktop/390/360px; no page errors.')
 }finally{await browser.close()}
})().catch(e=>{console.error(e);process.exit(1)})
