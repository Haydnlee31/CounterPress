const {chromium}=require('playwright')
const assert=require('node:assert/strict')
const fs=require('node:fs')
;(async()=>{
 const browser=await chromium.launch({headless:true,...(process.env.CHROME_EXECUTABLE?{executablePath:process.env.CHROME_EXECUTABLE}:{})})
 try {
  const page=await browser.newPage({viewport:{width:1440,height:1100},reducedMotion:'reduce'})
  const errors=[];page.on('pageerror',e=>errors.push(e.message))
  const base=process.argv[2]||'http://127.0.0.1:8010'
  await page.goto(`${base}/#matchday`)
  await page.getByRole('link',{name:'GI',exact:true}).click()
  await page.getByRole('heading',{name:'Eastbridge 4 – 2 Northport'}).waitFor()
  assert.equal(await page.getByRole('region',{name:'Goal timeline'}).getByRole('button').count(),6)
  assert.equal(await page.locator('.gi-stats strong').allTextContents().then(x=>x.join(',')),'22,7,759,143')
  await page.getByRole('group',{name:'Team',exact:true}).getByRole('button',{name:'Eastbridge',exact:true}).click()
  assert.equal(await page.locator('.gi-stats strong').allTextContents().then(x=>x.join(',')),'8,1,241,55')
  await page.getByRole('group',{name:'Explore actions'}).getByRole('button',{name:'Unsuccessful passes',exact:true}).click()
  assert.equal(await page.locator('.gi-action-list button').count(),40)
  await page.getByRole('button',{name:/Show more actions/}).click()
  assert.equal(await page.locator('.gi-action-list button').count(),55)
  await page.locator('.gi-action-list button').nth(2).click()
  await page.getByRole('region',{name:'Selected action'}).getByRole('heading',{name:'Pass unsuccessful'}).waitFor()
  assert.equal(await page.locator('.gi-pitch line').count(),1)
  await page.getByLabel('Player',{exact:true}).selectOption({label:'Theo Ashford · Eastbridge'})
  await page.getByRole('group',{name:'Period',exact:true}).getByRole('button',{name:'2nd half'}).click()
  assert(await page.locator('.gi-results').innerText().then(x=>x.includes('Theo Ashford')))
  await page.getByRole('button',{name:'Reset filters'}).click()
  await page.getByRole('region',{name:'Goal timeline'}).getByRole('button').first().click()
  await page.getByRole('region',{name:'Selected action'}).getByRole('heading',{name:'Own goal',exact:true}).waitFor()
  await page.getByRole('button',{name:'Next action →'}).click()
  assert.notEqual(await page.locator('.gi-detail-heading h2').innerText(),'Own goal')
  await page.getByRole('group',{name:'Explore actions'}).getByRole('button',{name:'Moments to review'}).click()
  await page.getByText(/A dangerous loss of the ball/).waitFor()
  assert.equal(await page.locator('pre').count(),0)
  assert.equal(await page.getByRole('link',{name:'Watch source match ↗'}).getAttribute('href'),'https://www.youtube.com/watch?v=GF-WteOINCc')
  fs.mkdirSync('var',{recursive:true})
  await page.getByRole('button',{name:'Reset filters'}).click()
  assert(!await page.locator('.gi-workspace').innerText().then(t=>/France|Croatia/.test(t)))
  await page.screenshot({path:'var/gi-desktop.png',fullPage:true})
  await page.getByRole('button',{name:/Shot map/}).click()
  assert.equal(await page.locator('.gi-shot-pin').count(),22)
  await page.getByRole('group',{name:'Team',exact:true}).getByRole('button',{name:'Northport',exact:true}).click()
  assert.equal(await page.locator('.gi-shot-pin').count(),14)
  await page.getByRole('group',{name:'Team',exact:true}).getByRole('button',{name:'Both clubs',exact:true}).click()
  await page.locator('.gi-shot-pin').last().focus();await page.keyboard.press('Enter')
  assert.equal(await page.getByRole('group',{name:'Explore actions'}).getByRole('button',{name:'All shots',exact:true}).getAttribute('aria-pressed'),'true')
  await page.screenshot({path:'var/gi-shot-map.png',fullPage:true})
  await page.getByRole('button',{name:'Selected play',exact:true}).click()
  await page.getByRole('button',{name:'Reset filters'}).click()
  for(const width of [390,360]) {
   await page.setViewportSize({width,height:844})
   assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),`overflow at ${width}`)
   await page.locator('.gi-action-list button').first().click()
   assert(await page.locator('#gi-detail').evaluate(e=>document.activeElement===e))
  }
  await page.screenshot({path:'var/gi-mobile.png',fullPage:true})
  await page.getByLabel('Player',{exact:true}).selectOption({label:'Eastbridge substitute 1 · Eastbridge'})
  await page.getByRole('group',{name:'Period',exact:true}).getByRole('button',{name:'1st half'}).click()
  await page.getByRole('heading',{name:'No plays in this view'}).waitFor()
  await page.getByRole('button',{name:'Show key moments',exact:true}).click()
  await page.getByRole('slider',{name:'Match timeline'}).focus()
  await page.keyboard.press('End')
  assert.equal(await page.getByRole('slider',{name:'Match timeline'}).inputValue(),'1461')
  await page.reload()
  await page.getByRole('heading',{name:'Eastbridge 4 – 2 Northport'}).waitFor()
  await page.getByRole('link',{name:'Skip to match intelligence'}).focus();await page.keyboard.press('Enter')
  assert.equal(new URL(page.url()).hash,'#gi')
  await page.route('**/api/gi/matches/**',route=>route.fulfill({status:503,body:'{}'}))
  await page.reload();await page.getByRole('heading',{name:'The match couldn’t load'}).waitFor()
  await page.unroute('**/api/gi/matches/**');await page.getByRole('button',{name:'Try again'}).click()
  await page.getByRole('heading',{name:'Eastbridge 4 – 2 Northport'}).waitFor()
  assert.deepEqual(errors,[])
  console.log('PASS GI canvas: fictional club labels, keyboard shot map (22 shots), real API, six goals, 22 shots, 759 passes, 143 unsuccessful passes; team/player/period filters, pagination, own-goal navigation, review context, mobile 390/360px, keyboard, retry; no page errors.')
 } finally {await browser.close()}
})().catch(e=>{console.error(e);process.exit(1)})
