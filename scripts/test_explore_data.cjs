const {chromium}=require('playwright')
const assert=require('node:assert/strict')
const fs=require('node:fs')
;(async()=>{
 const browser=await chromium.launch({headless:true,...(process.env.CHROME_EXECUTABLE?{executablePath:process.env.CHROME_EXECUTABLE}:{})})
 try{
  const page=await browser.newPage({viewport:{width:1440,height:1100},reducedMotion:'reduce'})
  const errors=[];page.on('pageerror',e=>errors.push(e.message))
  const base=process.argv[2]||'http://127.0.0.1:8010'
  fs.mkdirSync('var',{recursive:true})
  for(const [id,title,total,finish,passes] of [['last-gasp','Last-second turnaround',10,7,4],['one-touch','Pass, move, finish',5,4,3],['breakaway','From halfway to goal',5,4,3]]){
   await page.goto(`${base}/?story=${id}#matchday`)
   await page.getByRole('link',{name:'Explore data',exact:true}).click()
   await page.getByRole('heading',{level:1,name:title}).waitFor()
   await page.getByRole('link',{name:'Skip to analysis',exact:true}).focus()
   await page.keyboard.press('Enter')
   assert.equal(new URL(page.url()).hash,'#explore')
   const timeline=page.getByRole('region',{name:'Highlight timeline'})
   await timeline.getByRole('button').first().waitFor()
   assert.equal(await timeline.getByRole('button').count(),total)
   assert.equal(await page.locator('.fan-pitch-player').count(),22)
   assert.equal(await page.locator('pre').count(),0)
   assert.equal(await page.locator('.explore-facts dd').nth(1).innerText(),String(passes))
   await page.locator('.explore-phases button').last().click()
   await page.waitForFunction(i=>Number(document.querySelector('input[aria-label="Replay position"]').value)===i*100,finish)
   await timeline.getByRole('button').first().click()
   await page.waitForFunction(()=>document.querySelector('.explore-phases button')?.getAttribute('aria-pressed')==='true')
   await page.locator('.explore-phases button').nth(1).click()
   assert(await page.locator('.explore-routes path').count()>0)
   await page.getByLabel('Show routes',{exact:true}).uncheck()
   assert.equal(await page.locator('.explore-routes path').count(),0)
   await page.getByLabel('Show routes',{exact:true}).check()
   await page.screenshot({path:`var/explore-${id}.png`,fullPage:true,animations:'disabled'})
   await page.getByRole('button',{name:'Finn Brooks, Eastbridge',exact:true}).focus()
   await page.keyboard.press('Enter')
   await page.getByText('No recorded ball action involves this player in this highlight.',{exact:true}).waitFor()
   await page.getByRole('button',{name:'Compare',exact:true}).click()
   await page.getByLabel('Second phase',{exact:true}).selectOption('2')
   assert.equal(await page.getByRole('table').locator('tbody tr').count(),4)
   await page.getByRole('button',{name:'Show second phase',exact:true}).click()
   await page.waitForFunction(i=>Number(document.querySelector('input[aria-label="Replay position"]').value)===i*100,finish)
   await page.getByRole('link',{name:/Back to highlight/}).click()
   await page.getByRole('heading',{level:1,name:title}).waitFor()
   assert(page.url().includes(`story=${id}#matchday`))
  }
  await page.getByRole('link',{name:'Explore data',exact:true}).click()
  await page.getByRole('button',{name:'Last-second turnaround',exact:true}).click()
  await page.locator('.explore-phases button').first().waitFor()
  assert.equal(new URL(page.url()).searchParams.get('story'),'last-gasp')
  await page.reload()
  await page.locator('.explore-phases button').first().waitFor()
  await page.setViewportSize({width:390,height:844})
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth))
  await page.locator('.explore-phases button').last().click()
  assert(await page.locator('#explore-pitch').evaluate(e=>e===document.activeElement))
  await page.getByRole('button',{name:'Theo Ashford, Eastbridge',exact:true}).click()
  assert(await page.locator('#explore-insights').evaluate(e=>e===document.activeElement))
  await page.getByRole('button',{name:/Back to pitch/}).click()
  assert(await page.locator('#explore-pitch').evaluate(e=>e===document.activeElement))
  await page.getByRole('button',{name:'Compare',exact:true}).click()
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth))
  await page.screenshot({path:'var/explore-mobile.png',fullPage:true,animations:'disabled'})
  await page.getByLabel('Language',{exact:true}).selectOption('zh-Hans')
  await page.getByRole('region',{name:'集锦时间线'}).waitFor()
  await page.getByRole('button',{name:'进攻过程',exact:true}).click()
  await page.getByRole('heading',{name:'机会是怎样形成的？',exact:true}).waitFor()
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth))
  await page.getByLabel('Language',{exact:true}).selectOption('en')
  await page.getByRole('button',{name:'Pass, move, finish',exact:true}).click()
  await page.locator('.explore-phases button').first().waitFor()
  await page.emulateMedia({reducedMotion:'no-preference'})
  await page.getByLabel('Pitch replay speed').selectOption('1.5')
  await page.getByRole('button',{name:/Play highlight/}).click()
  await page.locator('.fan-goal-banner').waitFor({timeout:20000})
  await page.waitForFunction(()=>document.querySelectorAll('.explore-phases button')[2]?.getAttribute('aria-pressed')==='true')
  assert.equal(await page.getByRole('region',{name:'Highlight timeline'}).locator('[aria-current=step]').count(),1)
  await page.getByRole('link',{name:/Advanced analysis/}).click()
  await page.getByLabel('Local viewer',{exact:true}).waitFor()
  assert.deepEqual(errors,[])
  console.log('PASS: all three Matchday-to-analysis journeys, 22-player pitch, phase/evidence seeking, route toggle, factual counts, keyboard player selection, honest empty involvement, phase comparisons, return links, refresh, mobile focus, bilingual and advanced tools; no browser errors.')
 }finally{await browser.close()}
})().catch(e=>{console.error(e);process.exitCode=1})
