const {chromium}=require('playwright')
const assert=require('node:assert/strict')
;(async()=>{
 const browser=await chromium.launch({headless:true,...(process.env.CHROME_EXECUTABLE?{executablePath:process.env.CHROME_EXECUTABLE}:{})})
 try{
  const page=await browser.newPage({viewport:{width:1440,height:1000}})
  const errors=[];page.on('pageerror',e=>errors.push(e.message))
  const base=process.argv[2]||'http://127.0.0.1:8010'
  await page.goto(`${base}/#gi`)
  await page.getByRole('heading',{name:'Eastbridge 4 – 2 Northport'}).waitFor()
  await page.locator('.cp-library summary').click()
  await page.getByRole('link',{name:/Eastbridge 3 – 2 Northport/}).click()
  await page.getByRole('heading',{name:'Eastbridge 3 – 2 Northport'}).waitFor()
  assert.equal(new URL(page.url()).searchParams.get('match'),'wyscout-2058007')
  await page.getByRole('heading',{name:'Back from two down.'}).waitFor()
  assert.equal(await page.locator('.gi-comparison strong').allTextContents().then(v=>v.slice(0,6).join(',')),'24,9,501,377,71,55')
  assert.equal(await page.getByRole('region',{name:'Goal timeline'}).getByRole('button').count(),5)
  await page.getByRole('region',{name:'Goal timeline'}).getByRole('button').last().click()
  await page.getByRole('button',{name:'Pause',exact:true}).waitFor()
  assert.equal(await page.locator('.gi-replay-player').count(),22)
  const chosen=await page.locator('.gi-detail-heading').innerText()
  assert(!/Belgium|Japan|France|Croatia/.test(await page.locator('.gi-workspace').innerText()))
  for(const width of [390,360]){
   await page.setViewportSize({width,height:844})
   assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth))
  }
  await page.screenshot({path:'var/match-library-comeback-mobile.png',fullPage:true})
  await page.locator('.cp-library summary').click()
  await page.getByRole('link',{name:/Eastbridge 4 – 2 Northport/}).click()
  await page.getByRole('heading',{name:'Eastbridge 4 – 2 Northport'}).waitFor()
  assert.equal(await page.getByRole('region',{name:'Goal timeline'}).getByRole('button').count(),6)
  await page.locator('.cp-library summary').click()
  await page.getByRole('link',{name:/Eastbridge 3 – 2 Northport/}).click()
  await page.getByRole('button',{name:'Moments',exact:true}).click()
  await page.locator('.gi-detail-heading').waitFor()
  assert.equal(await page.locator('.gi-detail-heading').innerText(),chosen)
  await page.getByRole('link',{name:'Matchday',exact:true}).click()
  await page.getByRole('link',{name:'Match Centre',exact:true}).click()
  await page.getByRole('heading',{name:'Eastbridge 3 – 2 Northport'}).waitFor()
  await page.locator('.cp-library summary').click()
  await page.getByRole('link',{name:/Eastbridge 2 – 2 Northport/}).click()
  await page.getByRole('heading',{name:'Eastbridge 2 – 2 Northport'}).waitFor()
  await page.getByText('Full time · All square · 4 goals',{exact:true}).waitFor()
  assert.equal(await page.getByRole('region',{name:'Goal timeline'}).getByRole('button').count(),4)
  assert.equal(await page.getByRole('link',{name:'Watch source match ↗'}).count(),0)
  await page.getByRole('region',{name:'Goal timeline'}).getByRole('button').last().click()
  await page.getByRole('button',{name:'Pause',exact:true}).waitFor()
  assert.equal(await page.locator('.gi-replay-player').count(),22)
  assert.equal(await page.locator('.gi-stats strong').allTextContents().then(x=>x[0]),'23')
  assert.equal(await page.locator('.gi-stats strong').allTextContents().then(x=>x[2]),'815')
  await page.setViewportSize({width:1440,height:1000})
  await page.screenshot({path:'var/calibrated-match-desktop.png',fullPage:true})
  await page.setViewportSize({width:360,height:844})
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth))
  const syntheticSelection=await page.locator('.gi-detail-heading').innerText()
  await page.reload()
  await page.getByRole('button',{name:'Moments',exact:true}).click()
  assert.equal(await page.locator('.gi-detail-heading').innerText(),syntheticSelection)
  assert.deepEqual(errors,[])
  console.log('PASS three-match library: generated 2–2 with 815 passes/23 shots/four goals, native selection restored, 1682-action comeback, 3–2 result, five goals, team statistics, 22-player autoplay, fictional labels, per-match state, workspace navigation, mobile 390/360px; no page errors.')
 }finally{await browser.close()}
})().catch(e=>{console.error(e);process.exit(1)})
