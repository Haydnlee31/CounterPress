const {chromium}=require('playwright')
const assert=require('node:assert/strict')
;(async()=>{
 const browser=await chromium.launch({headless:true,...(process.env.CHROME_EXECUTABLE?{executablePath:process.env.CHROME_EXECUTABLE}:{})})
 try{
  const page=await browser.newPage({viewport:{width:1440,height:1000}})
  const errors=[];page.on('pageerror',e=>errors.push(e.message))
  const base=process.argv[2]||'http://127.0.0.1:8010'
  const match='synthetic-32fe41c5d304ce68d7d9'
  for(const [id,title] of [['level-first','Cole brings it level'],['take-lead','Hayes puts Eastbridge ahead'],['level-late','Fletcher answers back']]){
   await page.goto(`${base}/?story=${id}&match=${match}#matchday`)
   await page.getByRole('heading',{level:1,name:title}).waitFor()
   await page.locator('.fan-pitch-player').first().waitFor()
   assert.equal(await page.locator('.fan-pitch-player').count(),22)
   assert((await page.locator('.fan-intro .fan-kicker').innerText()).includes('18 Oct 2026'))
   await page.getByRole('button',{name:/Play highlight/}).click()
   await page.waitForTimeout(800)
   assert(Number(await page.getByRole('slider',{name:'Replay position'}).inputValue())>0)
   await page.getByRole('link',{name:'Explore data',exact:true}).click()
   await page.getByRole('heading',{level:1,name:title}).waitFor()
   await page.locator('.explore-timeline li').first().waitFor()
   assert.equal(await page.locator('.explore-timeline li').count(),6)
   await page.getByRole('link',{name:'Match Centre',exact:true}).click()
   await page.getByRole('heading',{name:'Eastbridge 2 – 2 Northport'}).waitFor()
   await page.getByText('18 Oct 2026',{exact:true}).waitFor()
  }
  await page.getByRole('region',{name:'Goal timeline'}).getByRole('button').last().click()
  await page.getByRole('button',{name:'Pause',exact:true}).waitFor()
  const capture=()=>page.locator('.gi-replay-player circle').evaluateAll(nodes=>nodes.map(n=>[n.getAttribute('cx'),n.getAttribute('cy')]))
  const a=await capture();await page.waitForTimeout(1000);const b=await capture();assert.notDeepEqual(a,b)
  const duration=await page.locator('.gi-playback>span').innerText()
  assert(Number(duration.match(/\/ (\d+)s/)[1])<20)
  await page.screenshot({path:'var/match-centre-paced-desktop.png',fullPage:true})
  await page.setViewportSize({width:390,height:844})
  await page.goto(`${base}/?story=level-late&match=${match}#matchday`)
  await page.locator('.fan-pitch-player').first().waitFor()
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth))
  await page.screenshot({path:'var/generated-highlight-mobile.png',fullPage:true})
  await page.goto(`${base}/?story=last-gasp#matchday`)
  await page.getByRole('heading',{name:'Last-second turnaround',exact:true}).waitFor()
  assert.equal(await page.locator('.fan-intro .fan-kicker').innerText(),'Preloaded')
  assert.deepEqual(errors,[])
  console.log('PASS paced Match Centre motion, bounded sequence duration, three derived highlights, six source actions each, 22 players, parent links, dates, Preloaded tags, desktop/mobile and Explore data.')
 }finally{await browser.close()}
})().catch(e=>{console.error(e);process.exit(1)})
