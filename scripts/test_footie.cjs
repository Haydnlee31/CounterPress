const {chromium}=require('playwright')
const assert=require('node:assert/strict')
;(async()=>{
 const browser=await chromium.launch({headless:true,executablePath:process.env.CHROME_EXECUTABLE||'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome'})
 try{
  const page=await browser.newPage({viewport:{width:1440,height:1000}}),errors=[]
  page.on('pageerror',e=>errors.push(e.message))
  const base=process.argv[2]||'http://127.0.0.1:8018'
  await page.goto(base+'/#assistant')
  await page.getByRole('heading',{name:'What caught your eye?'}).waitFor()
  await page.screenshot({path:'var/footie-desktop.png',fullPage:true})
  await page.getByRole('button',{name:/01.*How many goals does Mateo Cross/}).click()
  await page.getByRole('heading',{name:'From the match records'}).waitFor()
  if(await page.locator('.ft-breakdown').count())await page.locator('.ft-breakdown summary').last().click()
  await page.getByText('Mateo Cross · career: 75 goals.',{exact:true}).waitFor()
  await page.getByText(/Check the numbers/).click()
  await page.getByText(/140\/140 recorded appearances/).waitFor()
  assert.equal(await page.getByRole('link',{name:'View Mateo Cross'}).getAttribute('href'),'#football/player/rh09')
  await page.screenshot({path:'var/footie-answer-desktop.png',fullPage:true})
  await page.getByRole('textbox',{name:'Ask a football question'}).fill('And last season?')
  await page.getByRole('button',{name:'Send question'}).click()
  await page.getByRole('heading',{name:'From the match records'}).nth(1).waitFor()
  if(await page.locator('.ft-breakdown').count())await page.locator('.ft-breakdown summary').last().click()
  await page.getByText('Mateo Cross · 2025-26: 14 goals.',{exact:true}).waitFor()
  for(const width of [390,360]){
   await page.setViewportSize({width,height:844})
   assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'horizontal overflow '+width)
   const nav=await page.getByRole('link',{name:'Footie',exact:true}).boundingBox();assert(nav.x+nav.width<=width,'Footie navigation hidden')
  }
  await page.screenshot({path:'var/footie-answer-mobile.png',fullPage:true})
  await page.setViewportSize({width:1440,height:1000})
  await page.getByRole('button',{name:/New conversation/}).click()
  await page.getByText('A match',{exact:true}).click()
  await page.getByRole('combobox',{name:'Match context'}).selectOption('career-showcase-southbank-redhaven')
  await page.getByRole('button',{name:'Explain the latest goal ↗'}).click()
  await page.getByRole('heading',{name:'Why the moment matters'}).waitFor()
  if(await page.locator('.ft-breakdown').count())await page.locator('.ft-breakdown summary').last().click()
  await page.getByText(/That was Mateo Cross’s 75th career goal/).last().waitFor()
  await page.getByRole('button',{name:'▶ Watch the goal'}).click()
  await page.getByRole('dialog').waitFor()
  await page.getByRole('button',{name:/^Pause/}).waitFor()
  await page.screenshot({path:'var/footie-replay.png',fullPage:true})
  await page.keyboard.press('Escape')
  await page.getByRole('button',{name:/New conversation/}).click()
  await page.getByRole('textbox',{name:'Ask a football question'}).fill('Predict the next match winner')
  await page.getByRole('button',{name:'Send question'}).click()
  await page.getByRole('heading',{name:'Let’s narrow it down'}).waitFor()
  assert.deepEqual(errors,[])
  console.log('PASS Footie: desktop, 390/360px, 75-goal answer, readable evidence, follow-up season, scope reset, milestone-to-replay, unsupported request, no browser errors.')
 }finally{await browser.close()}
})().catch(e=>{console.error(e);process.exit(1)})
